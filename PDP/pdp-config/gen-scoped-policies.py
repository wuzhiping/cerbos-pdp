"""Generate the Cerbos policies for the FDEP providers.

    python3 pdp-config/gen-scoped-policies.py
    python3 pdp-config/gen-scoped-policies.py --verify

**The shape of one call.** FDEP's app id is `@<org>.<c4-path>.<operation>` —
the last segment is the operation, everything before it is the C4 path, and
the path is a folder path:

    @jev.systemone.LAYA.Choice
      │    │            └──► operation = Choice
      │    └───────────────► C4 path = systemone.LAYA
      └────────────────────► org      = jev

There is **no scope**. The provider goes into the kind:

    kind   = namespace.task_queue.workflow      pip.JEV.LAYA
    id     = the C4 path                       systemone.LAYA
    action = the plugin file                   Choice.py
    attr   = { accessMode, riskLevel }

So there is **one policy per provider** — no chain, no levels to keep
complete, and nothing that can fall out of sync. Measured: a colon-separated
kind needs no ancestor kinds, and a scope-free request is answered by the
policy for (kind, "") — the one that is there.

**The app family is separated by the id.** A rule about one family carries
`R.id == "<c4 path>"`, and the generator adds that itself — the author of a
rule only says what is true *of that family*.

**Where the rules come from.** Two sources, merged per provider:

    pdp-config/general-rules.yaml   the same for every provider
    orgs.yaml → orgs[].apps[].rules  that app family's own rules

Two sources contributing the same rule name with different content is a
conflict, and it is an error rather than a silent overwrite.
"""

from __future__ import annotations

import argparse
import pathlib
import sys
from typing import Any

import yaml

HEADER = """# yaml-language-server: $schema=https://api.cerbos.dev/latest/cerbos/policy/v1/Policy.schema.json
#
# {kind} — the {name} provider.
#
# GENERATED by pdp-config/gen-scoped-policies.py from pdp-config/orgs.yaml
# and pdp-config/general-rules.yaml. Do not edit by hand: the next run
# overwrites this file.
#
# ── The shape of one call ───────────────────────────────────────────────────
# FDEP's app id is `@<org>.<c4-path>.<operation>`:
#
#     kind   = {kind}          namespace.task_queue.workflow
#     id     = <c4 path>       e.g. systemone.LAYA
#     action = <operation>      e.g. Choice
#     attr   = {{ accessMode, riskLevel }}
#
# There is no scope: the provider is the kind, and the app family inside it
# is the id. So one policy covers one provider, and the families are told
# apart by `R.id`.
#
# The rules here are {rules_comment}.
"""

POLICY = """
apiVersion: api.cerbos.dev/v1

resourcePolicy:
  resource: {kind}
  version: default
{schemas}  rules:
{rules}"""

#: The schema the resource is validated against. Only declared while the
#: attributes are in use — a schema that validates `accessMode` and
#: `riskLevel` is itself a function of `R.attr`.
SCHEMAS = """  schemas:
    resourceSchema:
      ref: cerbos:///fdep.json

"""

#: The schema every FDEP resource is validated against.
SCHEMA_REF = "cerbos:///fdep.json"


class _IndentedDumper(yaml.SafeDumper):
    """A dumper that indents a block sequence under its key.

    PyYAML puts a sequence at the same indent as the key that holds it,
    which is valid but reads differently from the hand-written policies
    next to it.
    """

    def increase_indent(self, flow: bool = False, indentless: bool = False):
        return super().increase_indent(flow, False)


def load(path: pathlib.Path, key: str) -> list[dict]:
    document = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return document.get(key) or []


def load_flag(path: pathlib.Path, key: str, default: bool = True) -> bool:
    """A boolean setting out of a configuration file."""
    document = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    value = document.get(key)
    return default if value is None else bool(value)


def reads_an_attribute(rule: dict) -> bool:
    """Whether a rule's condition reads `R.attr`.

    `attributes: false` switches such a rule off **entirely** — the
    condition is what made the rule narrow, and dropping only the
    condition would widen the grant.
    """
    condition = rule.get("condition") or {}
    expr = (condition.get("match") or {}).get("expr", "")
    return "R.attr" in expr


def _significant(text: str) -> str:
    """The text without the trailing whitespace.

    The "was this file edited?" check compares the *meaning* of the file:
    a trailing newline that one editor adds and another does not is not an
    edit, and treating it as one would block the generator over nothing.
    """
    return text.rstrip() + "\n"


def file_name(kind: str) -> str:
    """The policy file's name — the kind itself.

    `pip.JEV.LAYA` -> `pip.JEV.LAYA.yaml`. The kind is
    `namespace.task_queue.workflow`, so the file name says what it is.
    """
    return kind


def store_name(kind: str) -> str:
    """The name the store keeps a kind under — the kind itself.

    `pip.JEV.LAYA` -> `resource.pip.JEV.LAYA.vdefault`.

    A **colon-separated** kind is rewritten by the store — `pip:JEV:LAYA`
    is kept as `resource.pip_JEV_LAYA.vdefault` — so the kind and its id
    would disagree. A dotted kind is kept as it is, and every spelling of
    the same thing is then the same string.
    """
    return kind


def render_rules(rules: list[dict]) -> str:
    """A rule list, as YAML, for the policy body."""
    if not rules:
        return "    []"
    text = yaml.dump(
        rules,
        Dumper=_IndentedDumper,
        sort_keys=False,
        allow_unicode=True,
        width=100,
    )
    return "\n".join("    " + line for line in text.rstrip("\n").splitlines())


def merge(*sources: tuple[str, list[dict]]) -> list[dict]:
    """Merge rule lists, refusing a conflict.

    A rule name is the identity. Two sources contributing the same name
    with different content is a conflict: the result would depend on the
    order, and nobody would notice.
    """
    merged: dict[str, dict] = {}
    for label, rules in sources:
        for rule in rules:
            name = rule.get("name")
            if not name:
                raise SystemExit(f"a rule from {label!r} has no name")
            existing = merged.get(name)
            if existing is None:
                merged[name] = rule
                continue
            if yaml.dump(existing, sort_keys=True) != yaml.dump(rule, sort_keys=True):
                raise SystemExit(
                    f"the rule {name!r} is defined differently by two sources "
                    f"({label!r} and the one already merged). "
                    f"Cerbos keeps one policy per kind, so one would silently "
                    f"replace the other."
                )
    return list(merged.values())


def for_family(rule: dict, path: str) -> dict:
    """A family rule, narrowed to that family by the resource id.

    The id is what tells the families apart, so the condition has to name
    it. The author of a rule only says what is true *of that family*.
    """
    narrowed = dict(rule)
    condition = narrowed.get("condition")
    expr = (condition or {}).get("match", {}).get("expr", "")
    family_test = f'R.id == "{path}"'
    expr = f"{family_test} && ({expr})" if expr else family_test
    narrowed["condition"] = {"match": {"expr": expr}}
    return narrowed


def compile_rule(rule: dict) -> dict:
    """A rule from the registry into a Cerbos rule.

    The two things the registry says and Cerbos wants differently:

    * **`principal`** — the principal's id. Cerbos has no `P.id` in a
      rule's role field, so the id becomes a condition (`P.id == "..."`)
      and the roles are set to `["*"]` — the wildcard that means
      "ignore the roles" (Cerbos' own documentation, note 12).

      This matters today: the platform sends `roles: ["guests"]` while the
      policies named `FDEP_GUEST`, so every role-based rule matched
      nothing and every call was refused.

    * **the actions** — the registry names the operations, and the action
      *is* the operation (`Choice`). The plugin file is where the
      operation lives (`Choice.py`), but that is the plugin's business.
    """
    compiled = dict(rule)

    principal = compiled.pop("principal", None)
    if principal:
        compiled["roles"] = ["*"]
        condition = compiled.get("condition") or {}
        expr = (condition.get("match") or {}).get("expr", "")
        id_test = f'P.id == "{principal}"'
        expr = f"{id_test} && ({expr})" if expr else id_test
        compiled["condition"] = {"match": {"expr": expr}}

    if "roles" not in compiled and "principal" not in compiled:
        # A rule without `roles` invalidates the whole policy, and the
        # family grants do not narrow by role — they are open. The
        # wildcard is what "ignore the roles" means.
        compiled["roles"] = ["*"]

    return compiled


def policy_body(
    kind: str,
    name: str,
    rules: list[dict],
    rules_comment: str,
    *,
    schema: bool = True,
) -> str:
    header = HEADER.format(
        kind=kind,
        name=name,
        rules_comment=rules_comment,
    )
    body = POLICY.format(
        kind=kind,
        schemas=SCHEMAS if schema else "",
        rules=render_rules(rules),
    )
    # A trailing newline: every text file has one, and a file without it
    # differs from every editor's version of the same text — which would
    # make the "hand-edited?" check fire on a file nobody touched.
    return header + body.rstrip("\n") + "\n"


def generate(
    orgs: list[dict],
    general: list[dict],
    out_root: pathlib.Path,
    *,
    attributes: bool = True,
) -> list[pathlib.Path]:
    written: list[pathlib.Path] = []
    switched_off: list[str] = []
    hand_edited: list[str] = []

    def usable(rules: list[dict]) -> list[dict]:
        if attributes:
            return rules
        kept = []
        for rule in rules:
            if reads_an_attribute(rule):
                switched_off.append(str(rule.get("name")))
                continue
            kept.append(rule)
        return kept

    for org in orgs:
        name = str(org.get("name") or "org")
        kind = str(org.get("kind") or "")
        if not kind:
            raise SystemExit(f"the org {name!r} has no kind")

        rules = [compile_rule(rule) for rule in usable(list(general))]
        for app in org.get("apps") or []:
            path = str(app.get("path") or "")
            if not path:
                raise SystemExit(f"the org {name!r} has an app with no path")
            for grant in app.get("grants") or []:
                rules.extend(
                    usable([compile_rule(for_family(grant, path))])
                )

        target = out_root / f"{file_name(kind)}.yaml"
        body = policy_body(
            kind, name, rules,
            "the general rules, plus each app family's own",
            schema=attributes,
        )

        if target.exists() and _significant(target.read_text(encoding="utf-8")) != _significant(body):
            # **A hand-edited policy is never overwritten.** The generated
            # file is a convenience, not the truth — the truth is what is
            # deployed. Silently replacing someone's edit would throw away
            # work that cannot be recovered, so the generator reports the
            # difference and leaves the file alone.
            hand_edited.append(target.name)
            print(f"  {name:10} {kind:20} -> {target.name}  ← 手改过,没覆盖")
            import difflib

            for line in difflib.unified_diff(
                target.read_text(encoding="utf-8").splitlines(),
                body.splitlines(),
                "文件里的",
                "生成的",
                lineterm="",
            ):
                print(f"      {line}")
            continue

        target.write_text(body, encoding="utf-8")
        written.append(target)
        print(f"  {name:10} {kind:20} -> {target.name}")

    if switched_off:
        print(
            "\n  被关掉的规则(依赖 R.attr):"
            + ", ".join(sorted(set(switched_off)))
            + "\n  打开 pdp-config/orgs.yaml 的 attributes: true 就能回来。"
        )

    if hand_edited:
        print(
            "\n  ⚠️ 手改过的 policy(没有覆盖):"
            + ", ".join(hand_edited)
            + "\n  注册表和这些文件已经不一致了 —— 要么把手改搬进注册表,"
            + "\n  要么把文件改回去。`--verify` 只查 store,不查这个。"
        )

    return written


def verify(orgs: list[dict], pdp_url: str, user: str, password: str) -> int:
    """Check that the store holds one policy per provider."""
    import httpx

    listed = httpx.get(
        f"{pdp_url}/admin/policies", auth=(user, password), timeout=15.0
    )
    if listed.status_code != 200:
        print(f"cannot read the store: HTTP {listed.status_code}", file=sys.stderr)
        return 1
    served = set(listed.json().get("policyIds") or [])

    missing = []
    for org in orgs:
        kind = str(org.get("kind") or "")
        policy_id = f"resource.{store_name(kind)}.vdefault"
        if policy_id not in served:
            missing.append(f"{org.get('name')}: {policy_id}")

    if missing:
        print("the store is missing:", file=sys.stderr)
        for entry in missing:
            print(f"  {entry}", file=sys.stderr)
        print(
            "\na request for a kind with no policy is NO_MATCH — every call of "
            "that provider is denied.",
            file=sys.stderr,
        )
        return 1

    print("the store holds one policy per provider")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="gen-scoped-policies.py")
    here = pathlib.Path(__file__).parent
    parser.add_argument("--orgs", type=pathlib.Path, default=here / "orgs.yaml")
    parser.add_argument(
        "--general", type=pathlib.Path, default=here / "general-rules.yaml"
    )
    parser.add_argument(
        "--out", type=pathlib.Path, default=pathlib.Path("policies"),
        help="where the policy files are written",
    )
    parser.add_argument("--verify", action="store_true", help="check the store")
    parser.add_argument("--pdp", default="http://10.17.1.201:3592")
    parser.add_argument("--user", default="cerbos")
    parser.add_argument("--password", default="cerbosAdmin")
    args = parser.parse_args(argv)

    orgs = load(args.orgs, "orgs")
    general = load(args.general, "rules")
    attributes = load_flag(args.orgs, "attributes", default=True)

    if not orgs:
        raise SystemExit(f"{args.orgs} lists no orgs")
    if not general:
        raise SystemExit(f"{args.general} lists no rules")

    if args.verify:
        return verify(orgs, args.pdp, args.user, args.password)

    print(f"orgs   : {args.orgs}")
    print(f"general: {args.general}")
    print(f"out    : {args.out}")
    print(f"R.attr : {'开' if attributes else '关'}")
    written = generate(orgs, general, args.out, attributes=attributes)
    print(f"\n{len(written)} 个 policy。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
